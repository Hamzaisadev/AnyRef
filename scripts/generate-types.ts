import fs from 'fs';
import path from 'path';
import dotenv from 'dotenv';

dotenv.config({ path: path.resolve(process.cwd(), '.env.local') });
dotenv.config({ path: path.resolve(process.cwd(), '.env') });

const supabaseUrl = process.env.NEXT_PUBLIC_SUPABASE_URL;
const serviceKey = process.env.SUPABASE_SERVICE_ROLE_KEY;

if (!supabaseUrl || !serviceKey) {
  console.error('Error: NEXT_PUBLIC_SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY must be set.');
  process.exit(1);
}

interface SwaggerProperty {
  type?: string;
  format?: string;
  description?: string;
  default?: string;
  items?: SwaggerProperty;
  enum?: string[];
}

interface SwaggerDefinition {
  type: string;
  required?: string[];
  properties: Record<string, SwaggerProperty>;
}

interface SwaggerSpec {
  definitions: Record<string, SwaggerDefinition>;
}

function mapPropertyType(prop: SwaggerProperty): string {
  if (prop.enum && prop.enum.length > 0) {
    return prop.enum.map((e) => `'${e}'`).join(' | ');
  }
  if (prop.format?.endsWith('[]') || prop.type === 'array') {
    if (prop.items) {
      return `${mapPropertyType(prop.items)}[]`;
    }
    const baseFormat = prop.format ? prop.format.replace('[]', '') : 'string';
    if (baseFormat === 'text' || baseFormat === 'varchar' || baseFormat === 'uuid') return 'string[]';
    if (baseFormat === 'integer' || baseFormat === 'numeric' || baseFormat === 'int4' || baseFormat === 'int8') return 'number[]';
    return 'unknown[]';
  }

  if (prop.format === 'json' || prop.format === 'jsonb') {
    return 'Json';
  }

  switch (prop.type) {
    case 'integer':
    case 'number':
      return 'number';
    case 'boolean':
      return 'boolean';
    case 'string':
      return 'string';
    default:
      if (prop.format === 'json' || prop.format === 'jsonb') return 'Json';
      return 'string';
  }
}

async function main() {
  console.log('📡 Fetching schema definition from Supabase PostgREST...');
  const res = await fetch(`${supabaseUrl}/rest/v1/`, {
    headers: {
      apikey: serviceKey!,
      Authorization: `Bearer ${serviceKey}`,
    },
  });

  if (!res.ok) {
    throw new Error(`Failed to fetch OpenAPI spec from PostgREST: ${res.status} ${res.statusText}`);
  }

  const spec = (await res.json()) as SwaggerSpec;
  const tables = Object.keys(spec.definitions || {}).sort();

  console.log(`Found ${tables.length} tables in public schema: ${tables.join(', ')}`);

  let code = `/* Auto-generated by scripts/generate-types.ts - DO NOT EDIT MANUALLY */

export type Json =
  | string
  | number
  | boolean
  | null
  | { [key: string]: Json | undefined }
  | Json[];

export interface Database {
  public: {
    Tables: {
`;

  for (const table of tables) {
    const def = spec.definitions[table];
    if (!def) continue;
    const props = def.properties || {};
    const requiredSet = new Set(def.required || []);

    code += `      ${table}: {\n`;

    // Row
    code += `        Row: {\n`;
    for (const [colName, prop] of Object.entries(props)) {
      const tsType = mapPropertyType(prop);
      const isRequired = requiredSet.has(colName);
      code += `          ${colName}: ${tsType}${isRequired ? '' : ' | null'};\n`;
    }
    code += `        };\n`;

    // Insert
    code += `        Insert: {\n`;
    for (const [colName, prop] of Object.entries(props)) {
      const tsType = mapPropertyType(prop);
      const hasDefault = prop.default !== undefined;
      const isRequired = requiredSet.has(colName) && !hasDefault;
      code += `          ${colName}${isRequired ? '' : '?'}: ${tsType}${requiredSet.has(colName) ? '' : ' | null'};\n`;
    }
    code += `        };\n`;

    // Update
    code += `        Update: {\n`;
    for (const [colName, prop] of Object.entries(props)) {
      const tsType = mapPropertyType(prop);
      code += `          ${colName}?: ${tsType}${requiredSet.has(colName) ? '' : ' | null'};\n`;
    }
    code += `        };\n`;
    code += `        Relationships: [];\n`;
    code += `      };\n`;
  }

  code += `    };\n    Views: {};\n    Functions: {};\n    Enums: {\n`;
  code += `      app_role: 'owner' | 'admin' | 'user';\n`;
  code += `      account_status: 'active' | 'suspended' | 'pending_deletion';\n`;
  code += `      entry_status: 'draft' | 'winner' | 'needs_tweak' | 'failed';\n`;
  code += `    };\n    CompositeTypes: {};\n  };\n}\n`;

  const targetDir = path.resolve(process.cwd(), 'src/types');
  if (!fs.existsSync(targetDir)) {
    fs.mkdirSync(targetDir, { recursive: true });
  }

  const targetFile = path.join(targetDir, 'database.types.ts');
  fs.writeFileSync(targetFile, code, 'utf-8');
  console.log(`✅ Supabase TypeScript types generated at ${targetFile}`);
}

main().catch((err) => {
  console.error('Type generation failed:', err);
  process.exit(1);
});
